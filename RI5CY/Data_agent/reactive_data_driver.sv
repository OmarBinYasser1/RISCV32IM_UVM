
class reactive_data_driver extends uvm_driver #(data_transaction);
  `uvm_component_utils(reactive_data_driver)

  virtual obi_data_if.driver_mp vif;

  data_transaction resp_tr;

  function new(string name = "reactive_data_driver", uvm_component parent = null);
    super.new(name, parent);
  endfunction

  function void build_phase(uvm_phase phase);
    super.build_phase(phase);
  endfunction

  task run_phase(uvm_phase phase);

    resp_tr = data_transaction::type_id::create("resp_tr");

    // Initialize interface signals
    reset_signals();

    forever begin
      // Wait for reset to clear
      // if (!vif.rst_n) begin
      if (!vif.cb_driver.rst_n) begin
        reset_signals();
        @(posedge vif.cb_driver.rst_n);
      end

      // 1. Wait for the core to issue a memory request
      @(posedge vif.cb_driver iff (vif.cb_driver.data_req_o === 1'b1 && vif.cb_driver.rst_n === 1'b1));

      // 2. Get the response transaction generated by your reactive sequence
      seq_item_port.get_next_item(resp_tr);

      // 3. Drive the Grant Phase using gnt_delay from the sequence item
      repeat (resp_tr.gnt_delay) @(posedge vif.cb_driver);
      vif.cb_driver.data_gnt_i <= 1'b1;

      // 4. Move to Response Phase (Next clock edge: drop gnt, drive rvalid & rdata)
      @(posedge vif.cb_driver);
      vif.cb_driver.data_gnt_i    <= 1'b0;
      vif.cb_driver.data_rvalid_i <= 1'b1;

      // Drive read data provided by the reactive sequence (ignored by core during writes)
      vif.cb_driver.data_rdata_i  <= resp_tr.data_rdata_i;

      // 5. De-assert response signals on next clock cycle
      @(posedge vif.cb_driver);
      vif.cb_driver.data_rvalid_i <= 1'b0;
      vif.cb_driver.data_rdata_i  <= 32'h0;

      // Handshake complete with sequence
      seq_item_port.item_done();
    end
  endtask

  task reset_signals();
    vif.cb_driver.data_gnt_i    <= 1'b0;
    vif.cb_driver.data_rvalid_i <= 1'b0;
    vif.cb_driver.data_rdata_i  <= 32'h0;
  endtask

endclass
